import os
import numpy as np
import torch
import yaml


def select_baseline_key(baseline_value: float) -> int:
    """Map a patient baseline glucose value to the appropriate model key."""
    if baseline_value > 120:
        return 120
    elif baseline_value > 100:
        return 100
    else:
        return -1


def load_config(path='configuration.yaml'):
    """
    Load a YAML configuration file and return the nested dict.
    Generated by the v14 training script (main_training14_regression_smaller_range.py).
    """
    with open(path, 'r', encoding='utf-8') as f:
        return yaml.full_load(f)


def _build_model_from_config(config):
    from models import SpecFormer, SpecFormer2
    model_cfg = config.get('model', {})
    data_cfg  = config.get('data', {})

    default_type = 'BANDENSEMBLE' if 'band_model' in config else 'SPECFORMER'
    model_type   = model_cfg.get('model_type', default_type).upper()
    seq_len          = data_cfg.get('sequence_length', model_cfg.get('sequence_length', 200))
    input_channels   = model_cfg.get('num_inputs', 16)
    num_classes      = model_cfg.get('num_classes', 1)
    d_model          = model_cfg.get('d_model', 128)
    nhead            = model_cfg.get('nhead', 8)
    num_encoder_layers = model_cfg.get('num_encoder_layers', 3)
    dim_feedforward  = model_cfg.get('dim_feedforward', 512)
    dropout          = model_cfg.get('dropout', 0.1)
    normalize_labels = data_cfg.get('normalize_labels', False)
    spectral_dropout = float(model_cfg.get('spectral_dropout', 0.0))
    conv_kernel_size = model_cfg.get('conv_kernel_size', 15)

    if model_type == 'BANDENSEMBLE':
        from models import BandEnsembleModel
        return BandEnsembleModel(
            seq_len=model_cfg.get('sequence_length', seq_len),
            input_channels=model_cfg.get('num_inputs', input_channels),
            band_width=model_cfg.get('band_width', 25),
            d_model=model_cfg.get('d_model', 128),
            normalize_labels=normalize_labels,
        )
    if model_type == 'SPECFORMER2':
        return SpecFormer2(
            seq_len=seq_len,
            input_channels=input_channels,
            num_classes=num_classes,
            d_model=d_model,
            nhead=nhead,
            num_encoder_layers=num_encoder_layers,
            dim_feedforward=dim_feedforward,
            conv_kernel_size=conv_kernel_size,
            dropout=dropout,
            normalize_labels=normalize_labels,
        )
    return SpecFormer(
        seq_len=seq_len,
        input_channels=input_channels,
        num_classes=num_classes,
        d_model=d_model,
        nhead=nhead,
        num_encoder_layers=num_encoder_layers,
        dim_feedforward=dim_feedforward,
        dropout=dropout,
        normalize_labels=normalize_labels,
        spectral_dropout=spectral_dropout,
    )


def load_model(path, config=None):
    # If the given path doesn't exist, try the other extension (.pt ↔ .pth)
    if not os.path.exists(path):
        alt = path[:-3] + '.pth' if path.endswith('.pt') else path[:-4] + '.pt'
        if os.path.exists(alt):
            path = alt
        else:
            raise FileNotFoundError(f"Model file not found: {path} (also tried {alt})")

    try:
        model = torch.jit.load(path, map_location='cpu')
        model.eval()
        model.to(torch.device('cpu'))
        print(f"Model loaded from {path} (TorchScript)")
        return model
    except RuntimeError:
        pass

    checkpoint = torch.load(path, map_location='cpu')
    if isinstance(checkpoint, dict):
        # Raw state dict — reconstruct the model architecture from config
        if config is None:
            raise ValueError(
                f"Cannot reconstruct model from state dict '{path}': config must be provided."
            )
        model = _build_model_from_config(config)
        model.load_state_dict(checkpoint)
    else:
        model = checkpoint

    model.eval()
    model.to(torch.device('cpu'))
    print(f"Model loaded from {path} (state dict)")
    return model


def wavelength_binning(cal_data, measure, dark, reference, bin_size=20):
    cal_data  = np.asarray(cal_data)
    measure   = np.asarray(measure)
    dark      = np.asarray(dark)
    reference = np.asarray(reference)
    measure_binned   = []
    dark_binned      = []
    reference_binned = []
    measure_binned2  = []
    dark_binned2     = []
    reference_binned2 = []
    bins = range(420, 750, bin_size)
    for b in bins:
        indices = np.argwhere((cal_data >= b) & (cal_data <= b + bin_size))
        measure_binned.append(np.nanmean(measure[indices]))
        dark_binned.append(np.nanmean(dark[indices]))
        reference_binned.append(np.nanmean(reference[indices]))
        measure_binned2.append(np.nanstd(measure[indices]))
        dark_binned2.append(np.nanstd(dark[indices]))
        reference_binned2.append(np.nanstd(reference[indices]))
    return (
        [np.hstack(measure_binned)],
        [np.hstack(dark_binned)],
        [np.hstack(reference_binned)],
        [np.hstack(measure_binned2)],
        [np.hstack(dark_binned2)],
        [np.hstack(reference_binned2)],
    )


def wavelength_binning2(cal_data, measure, dark, reference, bin_size=1):
    cal_data = np.asarray(cal_data)
    measure = np.asarray(measure)
    dark = np.asarray(dark)
    reference = np.asarray(reference)

    eps = 1e-8
    num = np.maximum(measure - dark, eps)
    den = np.maximum(reference - dark, eps)
    absorption = -np.log10(num / den)

    measure_binned, dark_binned, reference_binned = [], [], []
    measure_binned2, dark_binned2, reference_binned2 = [], [], []
    absorption_binned, absorption_binned2 = [], []

    for bin_start in range(420, 750, bin_size):
        indices = np.argwhere((cal_data >= bin_start) & (cal_data <= bin_start + bin_size))
        measure_binned.append(np.nanmean(measure[indices]))
        dark_binned.append(np.nanmean(dark[indices]))
        reference_binned.append(np.nanmean(reference[indices]))
        measure_binned2.append(np.nanstd(measure[indices]))
        dark_binned2.append(np.nanstd(dark[indices]))
        reference_binned2.append(np.nanstd(reference[indices]))
        absorption_binned.append(np.nanmean(absorption[indices]))
        absorption_binned2.append(np.nanstd(absorption[indices]))

    return (
        [np.hstack(measure_binned)], [np.hstack(dark_binned)], [np.hstack(reference_binned)],
        [np.hstack(absorption_binned)],
        [np.hstack(measure_binned2)], [np.hstack(dark_binned2)], [np.hstack(reference_binned2)],
        [np.hstack(absorption_binned2)],
    )


def add_spectral_derivatives(x_np, derivative_order=1):
    """
    Append spectral derivative channels along axis=1.
    Mirrors add_spectral_derivatives() from the research training code.

    Args:
        x_np: numpy array [batch, channels, wavelengths]
        derivative_order: 1 = first derivative only, 2 = first and second

    Returns:
        numpy array with derivative channels appended
    """
    first_deriv = np.gradient(x_np, axis=2)
    x_np = np.concatenate([x_np, first_deriv], axis=1)
    if derivative_order >= 2:
        second_deriv = np.gradient(first_deriv, axis=2)
        x_np = np.concatenate([x_np, second_deriv], axis=1)
    return x_np


def apply_per_channel_snv(x_tensor):
    """
    Apply per-channel SNV normalization and concatenate with the original.
    Matches NormalizedTensorDataset._normalize_sample(norm_method='snv', per_channel_norm=True).

    Args:
        x_tensor: torch.Tensor [batch, channels, wavelengths]

    Returns:
        torch.Tensor [batch, channels*2, wavelengths]
    """
    mean     = x_tensor.mean(dim=2, keepdim=True)
    std      = x_tensor.std(dim=2, keepdim=True)
    safe_std = torch.where(std < 1e-8, torch.ones_like(std), std)
    x_snv    = (x_tensor - mean) / safe_std
    return torch.cat([x_tensor, x_snv], dim=1)


def preprocess_for_inference(measure, reference, dark, cal_data, config, pop_avg=None):
    """
    Preprocess raw sensor data for model inference, driven by a YAML config dict.

    Channel order (use_signal_std=False, default for v14):
        0: measure, 1: dark, 2: reference, [3: absorption_computed  if use_absorption]
        → 4 base channels → 8 after derivatives → 16 after SNV concat
          [+8 population-normalize channels if population_normalize=True → 24 total]

    Channel order (use_signal_std=True, legacy):
        0: measure, 1: measure_std, 2: dark, 3: dark_std, 4: reference, 5: reference_std,
        [6: absorption, 7: absorption_std  if use_absorption]
        → 8 base channels → 16 after derivatives → 32 after SNV concat

    Pipeline:
        1. Wavelength binning (1nm bins, means + stds)
        2. Stack channels -> [1, C, N_wl]
        3. Filter to configured wavelength range
        4. Append absorption channel if use_absorption=True
        5. Add spectral derivatives if add_spectral_derivatives=True
        6. Compute population-normalize channels if population_normalize=True and pop_avg given
        7. Convert to torch.double tensor
        8. Apply per-channel SNV + concat if per_channel_norm=True
        9. Append population-normalize tensor if population_normalize=True

    Args:
        pop_avg: numpy array [C, W] (training-set mean, post-derivatives); required when
                 config has population_normalize=True. Ignored otherwise.

    Returns:
        torch.Tensor ready for model inference, e.g. [1, 16, 200] or [1, 32, 200]
    """
    wl_range             = config.get('data', {}).get('wavelength_nm_range', [450, 650])
    use_absorption       = config.get('data', {}).get('use_absorption', True)
    use_signal_std       = config.get('data', {}).get('use_signal_std', True)
    population_normalize = config.get('data', {}).get('population_normalize', False)
    wl_start             = int(wl_range[0])
    wl_end               = int(wl_range[1])
    add_deriv            = config.get('spectral', {}).get('add_spectral_derivatives', False)
    deriv_order          = int(config.get('spectral', {}).get('derivative_order', 1))
    per_channel_norm     = config.get('normalization', {}).get('per_channel_norm', False)

    # Step 1: wavelength binning (means + stds)
    measure_b, dark_b, reference_b, measure_std_b, dark_std_b, reference_std_b = wavelength_binning(
        cal_data, measure, dark, reference, bin_size=1
    )
    measure_b       = np.array(measure_b[0])
    dark_b          = np.array(dark_b[0])
    reference_b     = np.array(reference_b[0])
    measure_std_b   = np.array(measure_std_b[0])
    dark_std_b      = np.array(dark_std_b[0])
    reference_std_b = np.array(reference_std_b[0])

    # Step 2: stack channels
    # With stds: [measure, measure_std, dark, dark_std, reference, reference_std] -> [1, 6, N_wl]
    # Without:   [measure, dark, reference]                                        -> [1, 3, N_wl]
    if use_signal_std:
        x = np.stack([measure_b, measure_std_b, dark_b, dark_std_b, reference_b, reference_std_b], axis=0)
    else:
        x = np.stack([measure_b, dark_b, reference_b], axis=0)
    x = np.expand_dims(x, axis=0)

    # Step 3: wavelength range filter
    start_idx = int(wl_start - 420)
    end_idx   = int(wl_end - 420)
    if start_idx < 0 or end_idx > x.shape[2] or start_idx >= end_idx:
        raise ValueError(f"Invalid wavelength range ({wl_start}, {wl_end}). Must be within 420-750nm.")
    x = x[:, :, start_idx:end_idx]

    # Step 4: absorption channel
    # With stds: channels are 0=measure, 1=measure_std, 2=dark, 3=dark_std, 4=reference, 5=reference_std
    # Without:   channels are 0=measure, 1=dark, 2=reference
    if use_absorption:
        eps = 1e-8
        if use_signal_std:
            m, sigma_m = x[:, 0, :], x[:, 1, :]
            d, sigma_d = x[:, 2, :], x[:, 3, :]
            r, sigma_r = x[:, 4, :], x[:, 5, :]
        else:
            m, d, r = x[:, 0, :], x[:, 1, :], x[:, 2, :]
            sigma_m = sigma_d = sigma_r = np.zeros_like(m)

        num = np.maximum(m - d, eps)
        den = np.maximum(r - d, eps)
        absorption = -np.log10(num / den)
        absorption = np.expand_dims(absorption, axis=1)
        x = np.concatenate([x, absorption], axis=1)

        if use_signal_std:
            # Absorption std via error propagation:
            # absorption = -log10(num/den), num = m-d, den = r-d
            ln10 = np.log(10)
            abs_std = np.sqrt(
                (sigma_m / (num * ln10)) ** 2 +
                ((den - num) * sigma_d / (num * den * ln10)) ** 2 +
                (sigma_r / (den * ln10)) ** 2
            )
            abs_std = np.expand_dims(abs_std, axis=1)
            x = np.concatenate([x, abs_std], axis=1)

    # Step 5: spectral derivatives
    if add_deriv:
        x = add_spectral_derivatives(x, deriv_order)

    # Step 6: population-normalize channels (computed pre-SNV, same as training)
    x_pop_np = None
    if population_normalize:
        if pop_avg is None:
            raise ValueError("population_normalize=True in config but no pop_avg was provided.")
        eps = 1e-8
        x_pop_np = (x - pop_avg[np.newaxis]) / (np.abs(pop_avg[np.newaxis]) + eps)  # [1, C, W]

    # Step 7: to double tensor
    x_tensor = torch.from_numpy(x).double().to(torch.device('cpu'))

    # Step 8: per-channel SNV + concat
    if per_channel_norm:
        x_tensor = apply_per_channel_snv(x_tensor)

    # Step 9: append population-normalize tensor
    if x_pop_np is not None:
        x_pop_tensor = torch.from_numpy(x_pop_np).double().to(torch.device('cpu'))
        x_tensor = torch.cat([x_tensor, x_pop_tensor], dim=1)

    return x_tensor


def regression_inference(model, x):
    """
    Run inference with a probabilistic regression model.

    Returns:
        (mu, log_var): both torch.Tensor of shape [1, 1]
    """
    model.eval()
    dtype = next(model.parameters()).dtype
    x = x.to(dtype)
    with torch.no_grad():
        out = model(x)
    # BandEnsembleModel returns (mu, log_var, band_outputs, weights); others return (mu, log_var)
    if isinstance(out, (tuple, list)) and len(out) == 4:
        mu, log_var = out[0], out[1]
    else:
        mu, log_var = out
    return mu, log_var
